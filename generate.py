"""Write the optional status layouts from the Deepwick palette.

Run from this directory: PYTHONPATH=../spec python3 generate.py
"""
from pathlib import Path

from deepwick_spec.palette import Palette, load_palette

HERE = Path(__file__).parent
FILES = {"powerline": "deepwick-status.conf", "plain": "deepwick-status-plain.conf"}

# open: into a segment from the left; close: out of it; thin: inside it; ropen/rthin: the right-hand versions.
GLYPHS = {
    "powerline": {"open": "", "close": "", "thin": "", "ropen": "", "rthin": ""},
    "plain": {"open": "", "close": " ", "thin": "|", "ropen": "", "rthin": "|"},
}

HEADERS = {
    "powerline": "# Needs a Nerd Font or a powerline-patched font; deepwick-status-plain.conf doesn't.\n",
    "plain": "# The deepwick-status.conf layout without powerline glyphs, for fonts that lack them.\n",
}


def render(palette: Palette, layout: str) -> str:
    c, g = {name: value.lower() for name, value in palette.colors.items()}, GLYPHS[layout]
    # Inactive tabs follow deepwick.conf's bell and activity styles, which the tab's own colors would hide.
    c["alert"] = f"#{{?window_bell_flag,{c['red']},#{{?window_activity_flag,{c['yellow']},{c['muted']}}}}}"

    def sep(fg: str, bg: str) -> str:
        return f"#[fg={c[fg]},bg={c[bg]},nobold,noitalics,nounderscore]"

    def text(fg: str, bg: str, bold: bool = False) -> str:
        attrs = ",bold" if bold else "#{?window_bell_flag,#,bold,}" if fg == "alert" else ""
        return f"#[fg={c[fg]},bg={c[bg]}{attrs}]"

    def tab(fg: str, bg: str) -> str:
        return (
            f"{sep('surface', bg)}{g['open']} {text(fg, bg)}#I {sep(fg, bg)}{g['thin']} "
            f"{text(fg, bg)}#W #F {sep(bg, 'surface')}{g['close']}"
        )

    left = f"{text('background', 'blue', bold=True)} #S {sep('blue', 'surface')}{g['close']}"
    right = (
        f"{sep('overlay', 'surface')}{g['ropen']}{text('foreground', 'overlay')} %Y-%m-%d "
        f"{sep('foreground', 'overlay')}{g['rthin']}{text('foreground', 'overlay')} %H:%M "
        f"{sep('teal', 'overlay')}{g['ropen']}{text('background', 'teal', bold=True)} #H "
    )
    return (
        "# Deepwick status layout for tmux (https://github.com/deepwick/tmux).\n"
        + HEADERS[layout]
        + "# Replaces status-left, status-right and the window formats. Load it after deepwick.conf.\n"
        "# Generated by generate.py.\n"
        'set -g status-justify left\n'
        'set -g status-right-length 60\n'
        f'set -g status-left "{left}"\n'
        f'set -g status-right "{right}"\n'
        f'set -g window-status-format "{tab("alert", "overlay")}"\n'
        f'set -g window-status-current-format "{tab("background", "teal")}"\n'
        'set -g window-status-separator ""\n'
    )


if __name__ == "__main__":
    palette = load_palette()
    for layout, name in FILES.items():
        (HERE / name).write_text(render(palette, layout), encoding="utf-8")
        print(f"wrote {name}")
